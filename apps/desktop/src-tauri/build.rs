/// Knock's built-in sprite packs (ADR 0038): every file under `art/packs`,
/// compiled into the app as `BUILTIN_PACKS` (pack folder, [(path, bytes)]),
/// so every way of installing Knock has them. The app checks them at start
/// like any other pack.
fn embed_builtin_packs() {
    let root = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("../../../art/packs");
    println!("cargo:rerun-if-changed={}", root.display());
    let mut packs: Vec<(String, Vec<(String, std::path::PathBuf)>)> = Vec::new();
    if let Ok(entries) = std::fs::read_dir(&root) {
        for e in entries.flatten() {
            let path = e.path();
            if !path.is_dir() {
                continue;
            }
            let name = e.file_name().to_string_lossy().into_owned();
            let mut files = Vec::new();
            collect(&path, "", &mut files);
            files.sort();
            packs.push((name, files));
        }
    }
    packs.sort();
    let mut out = String::from(
        "/// Generated by build.rs from art/packs.\n#[allow(clippy::type_complexity)]\npub static BUILTIN_PACKS: &[(&str, &[(&str, &[u8])])] = &[\n",
    );
    for (name, files) in &packs {
        out += &format!("    ({name:?}, &[\n");
        for (rel, abs) in files {
            let abs = abs.canonicalize().expect("built-in pack file");
            out += &format!(
                "        ({rel:?}, include_bytes!({:?})),\n",
                abs.display().to_string()
            );
        }
        out += "    ]),\n";
    }
    out += "];\n";
    let dest =
        std::path::Path::new(&std::env::var("OUT_DIR").expect("OUT_DIR")).join("builtin_packs.rs");
    std::fs::write(dest, out).expect("write builtin_packs.rs");
}

/// Every file under `dir`, with its path relative to the pack (`/`-separated).
fn collect(dir: &std::path::Path, prefix: &str, out: &mut Vec<(String, std::path::PathBuf)>) {
    println!("cargo:rerun-if-changed={}", dir.display());
    let Ok(entries) = std::fs::read_dir(dir) else {
        return;
    };
    for e in entries.flatten() {
        let name = e.file_name().to_string_lossy().into_owned();
        let rel = if prefix.is_empty() {
            name
        } else {
            format!("{prefix}/{name}")
        };
        let path = e.path();
        if path.is_dir() {
            collect(&path, &rel, out);
        } else {
            out.push((rel, path));
        }
    }
}

fn main() {
    embed_builtin_packs();
    let manifest = tauri_build::AppManifest::new().commands(COMMANDS);
    tauri_build::try_build(tauri_build::Attributes::new().app_manifest(manifest))
        .expect("tauri build failed");
}
